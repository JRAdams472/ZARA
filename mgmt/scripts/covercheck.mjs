#!/usr/bin/env node
// covercheck — per-area coverage floor for the mgmt plane (LOLA/ISPPr
// convention, adapted). Reads vitest's lcov output:
//
//   npm run coverage          # vitest --coverage → coverage/lcov.info
//   node scripts/covercheck.mjs coverage/lcov.info [-floor 80] [-goal 85]
//
// Rules:
//   * every "major code area" must meet -floor percent or the check
//     fails — uniformity matters, no ten files at 100% and one at 0%;
//   * areas group as src/<subdir>/ (auth, db, kms, log, plugins,
//     redact, routes) + src/ root files;
//   * -goal is the overall target — reported, not enforced;
//   * test files never need tests; src/server.ts is the composition
//     root — verified by live/compose boot, not unit coverage (sibling
//     Program.cs convention);
//   * generated files ("DO NOT EDIT"/"<auto-generated") exempt.

import { readFileSync, existsSync } from "node:fs";
import { posix } from "node:path";

const args = process.argv.slice(2);
const flag = (n, d) => {
  const i = args.indexOf(`-${n}`);
  return i === -1 ? d : Number(args[i + 1]);
};
const FLOOR = flag("floor", 80);
const GOAL = flag("goal", 85);
const flagValueIdx = new Set(
  ["floor", "goal"].map((n) => args.indexOf(`-${n}`) + 1).filter((i) => i > 0)
);
const files = args.filter((a, i) => !a.startsWith("-") && !flagValueIdx.has(i));

if (!files.length || files.some((f) => !existsSync(f))) {
  console.error(`usage: covercheck <lcov.info> [more.info ...] [-floor 80] [-goal 85]`);
  process.exit(2);
}

// Path roots that anchor a repo-relative path inside an lcov SF: record.
const ROOT_MARKERS = ["/src/"];

const SKIP_FILE = [
  /(\.test\.[jt]sx?|\.spec\.[jt]sx?)$/,
  /__tests__\//,
  /(^|\/)server\.ts$/, // composition root — live-verified, not unit-covered
];
const SKIP_AREA = [/^\.$/, /(^|\/)node_modules\//, /^coverage\//, /^dist\//];

function isGenerated(path) {
  try {
    const head = readFileSync(path, "utf8").slice(0, 400);
    return head.includes("DO NOT EDIT") || head.includes("<auto-generated");
  } catch {
    return false; // source gone (CI may check paths from another dir) — don't exempt
  }
}

// lcov: "SF:<path>" ... "DA:line,hits" ... "end_of_record"
function parseLcov(text) {
  const files = new Map();
  let cur = null;
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (line.startsWith("SF:")) {
      let p = line.slice(3).replaceAll("\\", "/");
      for (const marker of ROOT_MARKERS) {
        const i = p.lastIndexOf(marker);
        if (i !== -1) { p = p.slice(i + 1); break; }
      }
      cur = files.get(p) ?? new Map();
      files.set(p, cur);
    } else if (line.startsWith("DA:") && cur) {
      const [ln, hits] = line.slice(3).split(",");
      cur.set(ln, (cur.get(ln) ?? 0) + Number(hits));
    }
  }
  return files;
}

// Area: src/<subdir>/ groups per-directory; src/ root files group as "src".
function areaOf(path) {
  const segs = path.split("/");
  return segs.length > 2 ? segs.slice(0, 2).join("/") : "src";
}

const merged = new Map();
for (const f of files) {
  for (const [path, lines] of parseLcov(readFileSync(f, "utf8"))) {
    const into = merged.get(path) ?? new Map();
    for (const [ln, hits] of lines) into.set(ln, (into.get(ln) ?? 0) + hits);
    merged.set(path, into);
  }
}

const areas = new Map(); // area -> [covered, total]
for (const [path, lines] of merged) {
  if (SKIP_FILE.some((r) => r.test(path)) || isGenerated(path)) continue;
  const area = areaOf(path);
  if (SKIP_AREA.some((r) => r.test(area))) continue;
  const [c, t] = areas.get(area) ?? [0, 0];
  let cov = 0;
  for (const hits of lines.values()) if (hits > 0) cov++;
  areas.set(area, [c + cov, t + lines.size]);
}

console.log(`\ncovercheck — floor ${FLOOR}%/area, goal ${GOAL}% overall\n`);
let fail = false;
let sumC = 0, sumT = 0;
for (const [area, [c, t]] of [...areas].sort((a, b) => a[0].localeCompare(b[0]))) {
  const pct = t ? (100 * c) / t : 100;
  sumC += c; sumT += t;
  const mark = pct < FLOOR ? "FAIL" : " ok ";
  if (pct < FLOOR) fail = true;
  console.log(` ${mark}  ${area.padEnd(20)} ${pct.toFixed(1).padStart(5)}%  (${c}/${t} lines)`);
}
const overall = sumT ? (100 * sumC) / sumT : 100;
console.log(`\n overall: ${overall.toFixed(1)}%  (goal ${GOAL}%)`);
if (overall < GOAL) console.log(` note: overall below ${GOAL}% goal — directional, not a hard gate`);
process.exit(fail ? 1 : 0);
